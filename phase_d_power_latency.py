"""Design Simulation 2 (design only): power for the prospective
secondary latency test (censoring-aware Cox model).

Implements PHASE_D_DESIGN_SIMULATION_PLAN.md, fixed before this run.
The archive primary Cox model (phase_c_latency_cox.py, at-risk
plants) supplies the baseline cumulative hazard and the pilot
coefficients for log intensity and theta_0. Event times for
simulated plants are generated by inverting the cumulative hazard
with the log-L0 coefficient replaced by scenario values
corresponding to HR 1.42 (pilot), HR 1.21 (half the pilot
log-hazard, prudent case) and HR 1.00 (null, archive size only).

Covariates are resampled jointly from the 213 paired archive rows
(phase_c_latency_times.csv). Plants with theta_0 >= 10 deg are
generated and then excluded from the at-risk analysis, as the
future analysis prespecifies. Censoring is at each resampled
plant's own last observation time. Each simulated experiment is
analysed with the prespecified Cox model (log L0 + log I + theta_0,
lifelines). 500 experiments per cell.

Planning approximation: event times assume proportional hazards
for generation, although the archive theta_0 term showed
non-proportionality. Treat powers as approximate.

Outputs: outputs/phase_d_power_latency.csv,
         outputs/phase_d_power_latency.json
Runtime: a few minutes. Requires lifelines.
"""

from __future__ import annotations

import json
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from lifelines import CoxPHFitter

HERE = Path(__file__).resolve().parent
OUT = HERE / "outputs"
REPS = 500
NGRID = [150, 213, 300, 450, 650, 900]
SCENARIOS = [("HR1.42_pilot", 1.42), ("HR1.21_prudent", 1.21)]


def fit_archive_cox():
    d = pd.read_csv(OUT / "phase_c_latency_times.csv")
    at = d[d.at_risk_10deg].copy()
    at["logL0"] = np.log(at.L0); at["logI"] = np.log(at.I)
    dd = at.rename(columns={"T_10deg": "T", "event_10deg": "E"})[
        ["T", "E", "logL0", "logI", "theta0"]]
    cph = CoxPHFitter()
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        cph.fit(dd, duration_col="T", event_col="E")
    base = cph.baseline_cumulative_hazard_
    times = base.index.to_numpy(float)
    haz = base.iloc[:, 0].to_numpy(float)
    keep = np.concatenate([[True], np.diff(haz) > 0])
    return cph, times[keep], haz[keep]


def simulate_cell(pool, cph, base_t, base_h, N, hr_true, rng):
    take = rng.integers(0, len(pool), size=N)
    src = pool.iloc[take]
    logL0 = np.log(src.L0.to_numpy()); logI = np.log(src.I.to_numpy())
    th = src.theta0.to_numpy(); t_last = src.t_last.to_numpy()
    beta = cph.params_
    lp = np.log(hr_true) * logL0 + beta["logI"] * logI \
        + beta["theta0"] * th
    # cumulative hazard for plant j: H0(t) * exp(lp_j); invert at -ln U
    target = -np.log(rng.random(N)) / np.exp(lp)
    t_event = np.interp(target, base_h, base_t,
                        left=base_t[0], right=np.inf)
    event = t_event <= t_last
    T = np.minimum(t_event, t_last)
    d = pd.DataFrame({"T": T, "E": event.astype(int),
                      "logL0": logL0, "logI": logI, "theta0": th})
    d = d[d.theta0 < 10.0]  # prespecified at-risk population
    if d.E.sum() < 20 or len(d) < 30:
        return None
    c = CoxPHFitter()
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        try:
            c.fit(d, duration_col="T", event_col="E")
        except Exception:
            return None
    s = c.summary.loc["logL0"]
    return {"p": float(s["p"]), "hr": float(np.exp(s["coef"])),
            "n_at_risk": int(len(d)), "events": int(d.E.sum())}


def main():
    pool = pd.read_csv(OUT / "phase_c_latency_times.csv")
    cph, base_t, base_h = fit_archive_cox()
    rng_master = np.random.default_rng(20261027)
    cells = [(name, hr, N) for name, hr in SCENARIOS for N in NGRID]
    cells.append(("HR1.00_null", 1.00, 213))
    rows = []
    for name, hr, N in cells:
        rng = np.random.default_rng(rng_master.integers(1 << 31))
        ps, hrs, ns, evs = [], [], [], []
        fails = 0
        for _ in range(REPS):
            r = simulate_cell(pool, cph, base_t, base_h, N, hr, rng)
            if r is None:
                fails += 1
                continue
            ps.append(r["p"]); hrs.append(r["hr"])
            ns.append(r["n_at_risk"]); evs.append(r["events"])
        ps = np.array(ps)
        rows.append({"scenario": name, "HR_true": hr,
                     "N_enrolled": N, "reps_ok": int(len(ps)),
                     "reps_failed": int(fails),
                     "power_or_typeI": float((ps < 0.05).mean()),
                     "mc_se": float(np.sqrt((ps < 0.05).mean()
                                            * (1 - (ps < 0.05).mean())
                                            / max(len(ps), 1))),
                     "mean_at_risk_n": float(np.mean(ns)),
                     "mean_events": float(np.mean(evs)),
                     "median_HR_hat": float(np.median(hrs))})
        print(f"{name} N={N}: power_or_typeI="
              f"{rows[-1]['power_or_typeI']:.3f} "
              f"(at-risk n={rows[-1]['mean_at_risk_n']:.0f})",
              flush=True)
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "phase_d_power_latency.csv", index=False)
    summary = {"archive_cox_coefficients": {
        k: float(v) for k, v in cph.params_.items()},
        "reps_per_cell": REPS, "N_grid": NGRID,
        "scenarios": [s[0] for s in SCENARIOS] + ["HR1.00_null"],
        "note": ("proportional hazards assumed for generation; "
                 "archive theta_0 term showed non-proportionality, "
                 "so powers are planning approximations"),
        "cells": rows}
    (OUT / "phase_d_power_latency.json").write_text(
        json.dumps(summary, indent=2))
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
